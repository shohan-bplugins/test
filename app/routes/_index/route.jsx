import { json, redirect } from "@remix-run/node";
import { CustomBox, CustomSpan, CustomButton } from "../../utils/polarisWebComponents";
import { Form, useLoaderData } from "@remix-run/react";
import { login } from "../../shopify.server";
import styles from "./styles.module.css";

export const loader = async ({ request }) => {
  const url = new URL(request.url);

  if (url.searchParams.get("shop")) {
    throw redirect(`/app?${url.searchParams.toString()}`);
  }

  return json({ showForm: Boolean(login) });
};

export default function App() {
  const { showForm } = useLoaderData();

  return (
    <CustomBox className={styles.index}>
      <CustomBox className={styles.content}>
        <h1 className={styles.heading}>A short heading about [your app]</h1>
        <p className={styles.text}>
          A tagline about [your app] that describes your value proposition.
        </p>
        {showForm && (
          <Form className={styles.form} method="post" action="/auth/login">
            <label className={styles.label}>
              <CustomSpan>Shop domain</CustomSpan>
              <input className={styles.input} type="text" name="shop" />
              <CustomSpan>e.g: my-shop-domain.myshopify.com</CustomSpan>
            </label>
            <CustomButton className={styles.button} type="submit">
              Log in
            </CustomButton>
          </Form>
        )}
        <ul className={styles.list}>
          <li>
            <strong>Product feature</strong>. Some detail about your feature and
            its benefit to your customer.
          </li>
          <li>
            <strong>Product feature</strong>. Some detail about your feature and
            its benefit to your customer.
          </li>
          <li>
            <strong>Product feature</strong>. Some detail about your feature and
            its benefit to your customer.
          </li>
        </ul>
      </CustomBox>
    </CustomBox>
  );
}
