// numeric id (as found in TopoJSON, possibly without leading zeros) -> alpha-2
export const NUM_TO_ALPHA2 = Object.entries(COUNTRIES).reduce((acc, [a2, v]) => {
  acc[v.num] = a2;
  acc[String(Number(v.num))] = a2; // also index without leading zeros
  return acc;
}, {});

export function countryName(code) {
  if (!code) return "Unknown";
  return COUNTRIES[code]?.name || code;
}

export function flagEmoji(code) {
  if (!code || code.length !== 2 || !/^[A-Za-z]{2}$/.test(code)) return "🏳️";
  const cc = code.toUpperCase();
  return String.fromCodePoint(...[...cc].map((c) => 0x1f1e6 + c.charCodeAt(0) - 65));
}
